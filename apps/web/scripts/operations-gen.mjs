// Builds the approved-operations manifest (ADR-0021) from src/graphql/operations.graphql:
// - src/graphql/persisted-operations.json  {sha256: text}, mounted into the gateway as
//   PERSISTED_OPERATIONS_PATH outside development;
// - src/graphql/operations.generated.ts     {name: {hash, text}}, used by the web app.
// `--check` fails if either file is out of date, without writing.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { Kind, parse, print } from 'graphql';

const dir = path.resolve(import.meta.dirname, '../src/graphql');
const source = readFileSync(path.join(dir, 'operations.graphql'), 'utf8');
const document = parse(source);

const operations = {};
const manifest = {};
for (const definition of document.definitions) {
  if (definition.kind !== Kind.OPERATION_DEFINITION || !definition.name) {
    throw new Error('every definition must be a named operation (no fragments yet)');
  }
  const name = definition.name.value;
  if (operations[name]) throw new Error(`duplicate operation name: ${name}`);
  const text = print(definition);
  const hash = createHash('sha256').update(text).digest('hex');
  operations[name] = { hash, text };
  manifest[hash] = text;
}

const json = `${JSON.stringify(manifest, null, 2)}\n`;
const ts = `// Generated by scripts/operations-gen.mjs from operations.graphql. Do not edit.\n\nexport const OPERATIONS = ${JSON.stringify(operations, null, 2)} as const;\n\nexport type OperationName = keyof typeof OPERATIONS;\n`;

const targets = [
  [path.join(dir, 'persisted-operations.json'), json],
  [path.join(dir, 'operations.generated.ts'), ts],
];

if (process.argv.includes('--check')) {
  const stale = targets.filter(([file, content]) => {
    try {
      return readFileSync(file, 'utf8') !== content;
    } catch {
      return true;
    }
  });
  if (stale.length > 0) {
    process.stderr.write(
      'operations are out of date: run pnpm --filter @chronos/web operations:gen\n',
    );
    process.exit(1);
  }
} else {
  for (const [file, content] of targets) writeFileSync(file, content);
}
